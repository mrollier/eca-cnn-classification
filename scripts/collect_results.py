"""Gather the training results into tables laid out like the chapter's.

    python scripts/collect_results.py                    # corrected-mode runs
    python scripts/collect_results.py --set mode=faithful

Reads ``output/runs/*/metrics.json`` and writes
``data/results/training_results[_faithful].md`` and ``.json``. Each value
sits next to the chapter's. A run that has not been trained shows as
"not run"; nothing is filled in from elsewhere.
"""

from __future__ import annotations

import argparse
import json

from eca_cnn.cli import RESULTS_DIR, add_config_args, config_from_args, write_json
from eca_cnn.config import expand_sweep, load_config

#: Chapter values (validation accuracy unless stated), keyed by run name.
CHAPTER = {
    "default_rules": {"train": 0.9986, "val": 0.9985},
    "default_classes": {"train": 0.9999, "val": 0.9999},
    "trimmed_classes": {"val": 0.9910},
    "trimmed_rules": {"val": 0.7119},
    "mlp_single_layer_classes": {"val": 0.95},
    "mlp_cropped_classes": {"val": 0.95},
    "final_classes": {"test": 0.9817},
    "final_independent": {"test": 0.6125},
}
#: Tab. assessment_data-augmentation: (rules, independent, classes) per row.
CHAPTER_TABLE = {
    "none": (0.7119, 0.8058, 0.9910), "invert": (0.2833, 0.8173, 0.9831), "mirror": (0.4885, 0.7881, 0.9866),
    "coarse_grain": (0.1575, 0.6535, 0.9783), "salt_and_pepper": (0.6654, 0.7552, 0.9718),
    "all": (0.2825, 0.5617, 0.9542),
}
OUTPUTS = ("rules", "independent", "classes")


def _pct(x):
    return "not run" if x is None else f"{100 * x:.2f}%"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_config_args(parser)
    args = parser.parse_args(argv)
    base = config_from_args(args)
    faithful = "__faithful" if base.faithful else ""
    runs_dir = base.path("output_dir") / "runs"

    def metrics(run_name):
        f = runs_dir / run_name / "metrics.json"
        if not f.exists():
            return None
        with open(f, encoding="utf-8") as fh:
            return json.load(fh)

    out = {"mode": base.mode, "runs": {}, "augmentation_table": {}}
    lines = [f"# Training results ({base.mode} mode)", "",
             "Generated by `scripts/collect_results.py` from `output/runs/*/metrics.json`.", "",
             "| Run | Set | This repository | Chapter | Epochs | Parameters |", "|---|---|---|---|---|---|"]
    for name, ref in CHAPTER.items():
        m = metrics(load_config(f"configs/{name}.yaml", {"mode": base.mode}).run_name)
        res = (m or {}).get("results", {})
        out["runs"][name] = m and {"results": res, "epochs_run": m["epochs_run"], "n_parameters": m["n_parameters"]}
        for s, chap in ref.items():
            acc = res.get(s, {}).get("accuracy")
            lines.append(f"| `{name}` | {s} | {_pct(acc)} | {_pct(chap)} | "
                         f"{m['epochs_run'] if m else ''} | {m['n_parameters'] if m else ''} |")

    lines += ["", "Augmentation table (validation accuracy; chapter value in brackets):", "",
              "| Augmentation | All rules (256) | Indep. rules (88) | LP classes (5) |", "|---|---|---|---|"]
    table_cfg = load_config("configs/augmentation_table.yaml", {"mode": base.mode})
    cells = {(c.name.split("__")[1].rsplit("_", 1)[0], c.model.output): c for c in expand_sweep(table_cfg)}
    for row, chap in CHAPTER_TABLE.items():
        vals = []
        for out_type, ref in zip(OUTPUTS, chap):
            m = metrics(cells[(row, out_type)].run_name)
            acc = (m or {}).get("results", {}).get("val", {}).get("accuracy")
            out["augmentation_table"][f"{row}/{out_type}"] = acc
            vals.append(f"{_pct(acc)} ({_pct(ref)})")
        lines.append(f"| {row} | " + " | ".join(vals) + " |")

    md = RESULTS_DIR / f"training_results{'_faithful' if faithful else ''}.md"
    md.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))
    write_json(out, md.with_suffix(".json"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
